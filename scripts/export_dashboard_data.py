#!/usr/bin/env python3
"""
Export LLM evaluation data from DuckDB database into static JS files 
for the high-fidelity portfolio web dashboard.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path
import duckdb

def get_db_path() -> Path:
    # Use environment variable first, check multiple fallback locations
    db_env = os.getenv("EVAL_DB_PATH")
    if db_env:
        path = Path(db_env)
        if path.exists():
            return path

    workspace_dir = Path(__file__).resolve().parent.parent
    
    # Paths relative to project root
    paths_to_check = [
        workspace_dir / "data" / "eval.duckdb",
        workspace_dir / "data" / "ci.duckdb"
    ]
    
    for path in paths_to_check:
        if path.exists():
            return path
            
    print("Error: Could not find evaluation DuckDB database.")
    sys.exit(1)

def export_data():
    db_path = get_db_path()
    print(f"Connecting to database: {db_path}")
    
    con = duckdb.connect(str(db_path), read_only=True)
    try:
        # Helper to convert SQL query directly to list of dicts
        def query_to_dicts(sql: str) -> list[dict]:
            res = con.execute(sql)
            columns = [col[0] for col in res.description]
            return [dict(zip(columns, row)) for row in res.fetchall()]

        print("Querying evaluation data models...")
        
        # 1. High-level run summaries
        run_summaries = query_to_dicts("SELECT * FROM int_run_summary ORDER BY run_started_at DESC")
        for r in run_summaries:
            if "run_started_at" in r and r["run_started_at"]:
                r["run_started_at"] = r["run_started_at"].isoformat()
        
        # 2. Pass rate by model
        pass_rates = query_to_dicts("SELECT * FROM mart_pass_rate_by_model ORDER BY model, subject_group")
        
        # 3. Category breakdown
        categories = query_to_dicts("SELECT * FROM mart_category_breakdown ORDER BY model, pass_rate DESC")
        
        # 4. Drift across runs
        drift = query_to_dicts("SELECT * FROM mart_run_drift ORDER BY model, run_seq")
        for r in drift:
            if "run_started_at" in r and r["run_started_at"]:
                r["run_started_at"] = r["run_started_at"].isoformat()
                
        # 5. Full joined completions (400 evals)
        completions_query = """
            SELECT 
                r.response_id,
                r.run_id,
                r.question_id,
                r.model,
                r.prompt_version,
                r.subject,
                r.subject_group,
                q.question,
                q.choice_a,
                q.choice_b,
                q.choice_c,
                q.choice_d,
                q.answer as ground_truth,
                r.parsed_answer,
                r.is_correct,
                r.latency_ms,
                r.input_tokens,
                r.output_tokens,
                resp.raw_completion
            FROM int_scored_responses r
            JOIN raw_mmlu_questions q ON r.question_id = q.question_id
            JOIN raw_eval_responses resp ON r.response_id = resp.response_id
            ORDER BY r.run_started_at DESC, r.subject, r.question_id
        """
        completions = query_to_dicts(completions_query)
        
        # Structure the final payload
        payload = {
            "metadata": {
                "source_db": db_path.name,
                "exported_at": Path("/").stat().st_mtime if hasattr(Path("/"), "stat") else None, 
                "total_runs": len(run_summaries),
                "total_completions": len(completions)
            },
            "runs": run_summaries,
            "pass_rates": pass_rates,
            "categories": categories,
            "drift": drift,
            "completions": completions
        }
        
        # Convert payload to standard JSON string
        json_data = json.dumps(payload, indent=2, default=str)
        js_content = f"// Automatically generated by scripts/export_dashboard_data.py\nwindow.EVAL_DATA = {json_data};\n"
        
        # Write to target files
        project_dir = Path(__file__).resolve().parent.parent
        
        targets = [
            project_dir / "docs" / "data.js",
            project_dir / "dashboard" / "data.js"
        ]
        
        for target in targets:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(js_content, encoding="utf-8")
            print(f"Successfully wrote {len(completions)} completions and metrics to: {target}")
            
    finally:
        con.close()

if __name__ == "__main__":
    export_data()
